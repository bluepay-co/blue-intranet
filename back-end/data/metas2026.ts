function normalizar(nome: string): string {
  return nome
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
}

export function getMetaIndividual(primeiroNome: string, mes: number, ano: number): number {
  if (ano !== 2026) return 0;
  const chave = normalizar(primeiroNome);
  const metas = METAS_INDIVIDUAIS_2026[chave];
  return metas ? (metas[mes - 1] ?? 0) : 0;
}

export function getMetaEquipe(equipe: 'KAM' | 'IS' | 'GERAL', mes: number, ano: number): number {
  if (ano !== 2026) return 0;
  const arr = equipe === 'KAM' ? META_KAM_2026 : equipe === 'IS' ? META_IS_2026 : META_TOTAL_2026;
  return arr[mes - 1] ?? 0;
}
